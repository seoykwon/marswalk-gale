#!/usr/bin/env python3
"""Stage 5-1: copy the parts of scripts/config.json that the web app shows into site/data/config.json.

  python3 -I scripts/50_export_config.py

The site must never read outside site/ (Plan/03), so the "Assumptions" disclosure and the shared
JS modules (routecalc/env) read this copy. Re-run after every change to scripts/config.json.

LET bins are no longer exported here: scripts/20_parse_rad.py stores them per period in
site/data/rad.json (periods.<p>.let.centre_keV_um / width_keV_um), read from each file (Plan/17 P2-5).

Note: Plan/03 reserved "50_eva_precache.py" for stage 5-5; the task brief named this file
50_export_config.py, so 5-5 should use another number (e.g. 55_eva_precache.py).
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'scripts', 'config.json')
OUT = os.path.join(ROOT, 'site', 'data', 'config.json')
KEYS = ['crs', 'walk', 'comms', 'rad', 'rems', 'eva']


def main():
    cfg = json.load(open(SRC))
    out = {
        '_comment': 'Generated by scripts/50_export_config.py from scripts/config.json (do not edit by hand). '
                    'Values marked assumption are not derived from data (Plan/05 Q4).',
        '_source_file': 'scripts/config.json',
    }
    for k in KEYS:
        out[k] = cfg[k]
    out['route_method'] = cfg['routes']['method']

    json.dump(out, open(OUT, 'w'), indent=1, ensure_ascii=False)
    print('wrote %s (%d bytes): %s + route_method' % (os.path.relpath(OUT, ROOT), os.path.getsize(OUT), ', '.join(KEYS)))


if __name__ == '__main__':
    main()
