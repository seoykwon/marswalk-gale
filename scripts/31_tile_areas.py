#!/usr/bin/env python3
"""High-zoom rectangles for stage 3 tiles (Plan/03 "타일 범위").

Writes scripts/31_tile_areas.json:
  hi_rects     <= 4 rectangles covering the rover traverse inside the HiRISE colour image (B2 z16,
               T1/T2/T3 z14-15). Found by splitting the traverse (waypoints in sol order) into 4
               consecutive pieces so that the summed z16 tile count of the buffered bboxes is minimal.
  route_areas  provisional route A/B areas (B2 z17, 10 m contours). Routes are fixed in stage 4, so
               these are generous: bbox of the plan-02 waypoint span + buffer.
Every route area is forced inside one hi_rect so z13-16 tiles exist for the EVA offline cache.

Run: python3 -I scripts/31_tile_areas.py
"""
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = 59274.7
B2 = (137.3267235, -4.8756048, 137.4785590, -4.5550633)  # w s e n
TRAV_BUF_M = 250
ROUTE_BUF_M = 400
ROUTE_SPANS = {  # plan 02 sec.2 (provisional, stage 4 fixes the real routes)
    'A': dict(sol_from=3, sol_to=130, note='Bradbury Landing (sol 3) -> Yellowknife Bay (sol 125-130)'),
    'B': dict(sol_from=4614, sol_to=4996, note='sol 4614 base -> sol 4841 -> sol 4996 (Mount Sharp slope)'),
}


def tiles(b, z):
    s = 180.0 / 2 ** z
    x0, x1 = math.floor((b[0] + 180) / s), math.floor((b[2] + 180) / s - 1e-12)
    y0, y1 = math.floor((90 - b[3]) / s), math.floor((90 - b[1]) / s - 1e-12)
    return x0, y0, x1, y1


def ntiles(b, z):
    x0, y0, x1, y1 = tiles(b, z)
    return (x1 - x0 + 1) * (y1 - y0 + 1)


def tileset(rects, z):
    st = set()
    for b in rects:
        x0, y0, x1, y1 = tiles(b, z)
        st.update((x, y) for x in range(x0, x1 + 1) for y in range(y0, y1 + 1))
    return st


def bbox(pts, buf_m):
    d = buf_m / M
    return [min(p[0] for p in pts) - d, min(p[1] for p in pts) - d,
            max(p[0] for p in pts) + d, max(p[1] for p in pts) + d]


def clip(b):
    return [max(b[0], B2[0]), max(b[1], B2[1]), min(b[2], B2[2]), min(b[3], B2[3])]


def contains(a, b):
    return a[0] <= b[0] and a[1] <= b[1] and a[2] >= b[2] and a[3] >= b[3]


def main():
    d = json.load(open(os.path.join(ROOT, 'Vector', 'MSL_traverse', 'MSL_waypoints.json')))
    wp = [f['properties'] for f in d['features']]
    pts = [(p['lon'], p['lat']) for p in wp]
    # route areas
    route_areas = []
    for rid, sp in ROUTE_SPANS.items():
        sel = [(p['lon'], p['lat']) for p in wp if sp['sol_from'] <= p['sol'] <= sp['sol_to']]
        route_areas.append(dict(id=rid, bbox=[round(v, 6) for v in clip(bbox(sel, ROUTE_BUF_M))],
                                n_waypoints=len(sel), buffer_m=ROUTE_BUF_M, provisional=True, **sp))
    # split traverse into 4 consecutive pieces (coarse index step for speed)
    step = 5
    idx = list(range(0, len(pts), step)) + [len(pts)]
    n = len(idx)
    cost = {}

    def seg_cost(i, j):
        k = (i, j)
        if k not in cost:
            b = clip(bbox(pts[idx[i]:idx[j]], TRAV_BUF_M))
            cost[k] = (ntiles(b, 16), b)
        return cost[k]

    best = None
    for a in range(1, n - 2):
        ca = seg_cost(0, a)[0]
        if best and ca >= best[0]:
            continue
        for b_ in range(a + 1, n - 1):
            cb = ca + seg_cost(a, b_)[0]
            if best and cb >= best[0]:
                continue
            for c in range(b_ + 1, n):
                tot = cb + seg_cost(b_, c)[0] + seg_cost(c, n - 1)[0] if c < n - 1 else None
                if tot is None:
                    continue
                if best is None or tot < best[0]:
                    best = (tot, (a, b_, c))
    a, b_, c = best[1]
    cuts = [(0, a), (a, b_), (b_, c), (c, n - 1)]
    rects = [seg_cost(i, j)[1] for i, j in cuts]
    # force each route area inside one rectangle (grow the one that overlaps it most)
    for ra in route_areas:
        rb = ra['bbox']
        if any(contains(r, rb) for r in rects):
            continue

        def overlap(r):
            w = min(r[2], rb[2]) - max(r[0], rb[0])
            h = min(r[3], rb[3]) - max(r[1], rb[1])
            return max(w, 0) * max(h, 0)
        k = max(range(4), key=lambda i: overlap(rects[i]))
        r = rects[k]
        rects[k] = [min(r[0], rb[0]), min(r[1], rb[1]), max(r[2], rb[2]), max(r[3], rb[3])]
    hi = []
    for k, ((i, j), r) in enumerate(zip(cuts, rects)):
        sols = [wp[t]['sol'] for t in range(idx[i], idx[j])]
        hi.append(dict(id='R%d' % (k + 1), bbox=[round(v, 6) for v in r], sol_from=min(sols),
                       sol_to=max(sols), z16_tiles=ntiles(r, 16),
                       size_km=[round((r[2] - r[0]) * M / 1000, 2), round((r[3] - r[1]) * M / 1000, 2)]))
    res = dict(
        _comment='Generated by scripts/31_tile_areas.py. bbox = [west, south, east, north] degrees '
                 '(+proj=longlat +R=3396190). route_areas are PROVISIONAL (stage 4 fixes routes).',
        traverse_buffer_m=TRAV_BUF_M, hi_rects=hi, route_areas=route_areas,
        z16_union_tiles=len(tileset([h['bbox'] for h in hi], 16)),
        z15_union_tiles=len(tileset([h['bbox'] for h in hi], 15)),
        z17_route_tiles=len(tileset([r['bbox'] for r in route_areas], 17)),
        b2_full_z15_tiles=ntiles(B2, 15))
    json.dump(res, open(os.path.join(ROOT, 'scripts', '31_tile_areas.json'), 'w'), indent=1)
    print(json.dumps(res, indent=1))


if __name__ == '__main__':
    main()
